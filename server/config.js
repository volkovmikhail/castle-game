/**
 * Конфигурация сервера и сессий. Один процесс Node обслуживает много комнат.
 */
export default {
  HTTP_PORT: Number(process.env.PORT) || 3000,

  /** Частота серверного тика симуляции (Phase 2). */
  TICK_HZ: 20,
  get TICK_MS() {
    return 1000 / this.TICK_HZ;
  },

  /** Как часто рассылать снапшот состояния клиентам (каждый N-й тик). */
  SNAPSHOT_EVERY_TICKS: 2,

  /** Лимиты лобби. */
  MIN_PLAYERS: 2,
  MAX_PLAYERS: 4,

  /** Длина кода комнаты (A-Z0-9, без похожих символов). */
  ROOM_CODE_LENGTH: 4,

  /**
   * Сколько подряд ошибок в тике одной комнаты допускаем перед её аварийной
   * остановкой. Изолирует баг одной сессии от остальных и от процесса.
   */
  MAX_TICK_ERRORS: 30,

  /** Пустая комната живёт ещё столько мс перед удалением из памяти. */
  EMPTY_ROOM_TTL_MS: 15_000,

  /**
   * Быстрый матч ("Find Game"): сколько ждём добора до MAX_PLAYERS, прежде чем
   * запустить партию с текущим числом игроков. Отсчёт стартует, как только в
   * очереди набралось MIN_PLAYERS. При MAX_PLAYERS игра стартует немедленно.
   * Переопределяется через env (удобно в тестах ускорить отсчёт).
   */
  MATCH_FILL_MS: Number(process.env.MATCH_FILL_MS) || 60_000,
};
